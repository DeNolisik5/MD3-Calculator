/** Extra round shapes, the "squircle" grammar of Material 3 Expressive. */
private val CalculatorShapes = Shapes(
    extraSmall = RoundedCornerShape(12.dp),
    small = RoundedCornerShape(18.dp),
    medium = RoundedCornerShape(24.dp),
    large = RoundedCornerShape(32.dp),
    extraLarge = RoundedCornerShape(40.dp),
)

/**
 * @param dynamicColor when true (default) the palette is derived from the
 * user's wallpaper on Android 12+, i.e. Material You.
 */
@Composable
fun CalculatorTheme(
    darkTheme: Boolean = isSystemInDarkThemeCompat(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = CalculatorTypography,
        shapes = CalculatorShapes,
        content = content,
    )
}

@Composable
private fun isSystemInDarkThemeCompat(): Boolean = androidx.compose.foundation.isSystemInDarkTheme()
